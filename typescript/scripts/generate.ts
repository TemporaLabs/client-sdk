// Generates src/generated/ and llms.txt from spec/openapi.json, the Tempora API's own OpenAPI document, and the MCP tool
// list from spec/tools.json, the API's published list, when the API has published one.
// Nothing under src/generated/ is edited by hand: change the API's document, copy it into spec/, and run
//   npm run generate
// It fails closed: a document this generator does not understand is an error, never a partial client.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

type Json = null | boolean | number | string | Json[] | { [k: string]: Json }
type Schema = { [k: string]: Json }
export type Spec = {
  openapi: string
  info: { title: string; version: string }
  paths: Record<string, Record<string, Schema>>
  components: { schemas: Record<string, Schema>; responses?: Record<string, Schema>; securitySchemes?: Record<string, Schema> }
}

// The client reads a lost answer as `unknown` only on a POST, so a write must be a POST; any other method fails generation.
const METHODS = ['get', 'post'] as const
const HEADER = '// Generated by scripts/generate.ts from spec/openapi.json. Do not edit by hand.\n'
/** The JSON Schema keywords the type printer understands. Anything else that shapes a type fails generation. */
const TYPE_KEYWORDS = new Set(['$ref', 'type', 'properties', 'required', 'enum', 'items', 'anyOf', 'oneOf', 'allOf', 'additionalProperties', 'const'])
/** Keywords that only narrow a value (checked at run time by the schema), never its TypeScript type. */
const NARROWING = new Set(['minLength', 'maxLength', 'pattern', 'format', 'minimum', 'maximum', 'exclusiveMinimum', 'exclusiveMaximum', 'minItems', 'maxItems', 'description', 'default', 'title', 'examples', 'readOnly', 'writeOnly', 'deprecated'])

const fail = (why: string): never => {
  throw new Error(`generate: ${why}`)
}
const isObj = (x: unknown): x is Schema => typeof x === 'object' && x !== null && !Array.isArray(x)
const refName = (ref: string) => (ref.startsWith('#/components/schemas/') ? ref.slice('#/components/schemas/'.length) : fail(`unsupported $ref ${ref}`))
const ident = (name: string) => (/^[A-Za-z_][A-Za-z0-9_]*$/.test(name) ? name : fail(`not an identifier: ${name}`))
const key = (name: string) => (/^[A-Za-z_][A-Za-z0-9_]*$/.test(name) ? name : JSON.stringify(name))

/** Keywords that each decide the whole type alone: the printer reads the first one present and nothing beside it. */
const WHOLE = ['$ref', 'anyOf', 'oneOf', 'allOf', 'enum', 'const'] as const
/** Keywords that shape a type. Beside a $ref or a composition, the printer would drop them. */
const SHAPING = ['type', 'properties', 'required', 'items', 'additionalProperties'] as const
/** An enum or a const fixes the value, so a scalar `type` beside one is harmless; anything that shapes an object or array is not. */
const BESIDE_VALUE = new Set<string>(['properties', 'required', 'items', 'additionalProperties'])

/** The TypeScript type a JSON Schema describes. */
export function tsType(s: Json | undefined): string {
  if (s === undefined || s === true) return 'unknown'
  if (!isObj(s)) return fail(`not a schema: ${JSON.stringify(s)}`)
  for (const k of Object.keys(s)) if (!TYPE_KEYWORDS.has(k) && !NARROWING.has(k)) fail(`unsupported keyword ${k}`)
  // Fail closed rather than print part of a schema: one deciding keyword, and nothing beside it that it would drop.
  const whole = WHOLE.filter((k) => k in s)
  if (whole.length > 1) fail(`${whole[0]} beside ${whole[1]}: the printer would drop one of them`)
  if (whole.length === 1) {
    const w = whole[0]!
    const dropped = SHAPING.filter((k) => k in s && (w === 'enum' || w === 'const' ? BESIDE_VALUE.has(k) : true))
    if (dropped.length > 0) fail(`${w} beside ${dropped.join(', ')}: the printer would drop ${dropped.length === 1 ? 'it' : 'them'}`)
  }
  if (typeof s.$ref === 'string') return ident(refName(s.$ref))
  if ('const' in s) return JSON.stringify(s.const)
  if (Array.isArray(s.anyOf)) return union(s.anyOf.map(tsType))
  if (Array.isArray(s.oneOf)) return union(s.oneOf.map(tsType))
  if (Array.isArray(s.allOf)) return s.allOf.map((x) => `(${tsType(x)})`).join(' & ')
  if (Array.isArray(s.enum)) return union(s.enum.map((v) => JSON.stringify(v)))
  const types = s.type === undefined ? [] : Array.isArray(s.type) ? s.type : [s.type]
  if (types.length === 0) {
    // A schema with no type takes any value at run time, but every schema inside it is still checked, so a
    // keyword the generator cannot represent fails here rather than vanishing into `unknown`.
    if (s.items !== undefined) tsType(s.items)
    return s.properties || s.additionalProperties !== undefined ? objectType(s) : 'unknown'
  }
  return union(types.map((t) => {
    switch (t) {
      case 'string': return 'string'
      case 'number':
      case 'integer': return 'number'
      case 'boolean': return 'boolean'
      case 'null': return 'null'
      case 'array': return `Array<${tsType(s.items)}>`
      case 'object': return objectType(s)
      default: return fail(`unsupported type ${JSON.stringify(t)}`)
    }
  }))
}

function union(parts: string[]): string {
  const unique = [...new Set(parts)]
  return unique.length === 1 ? unique[0]! : unique.map((p) => (p.includes(' & ') ? `(${p})` : p)).join(' | ')
}

function objectType(s: Schema): string {
  const props = isObj(s.properties) ? s.properties : {}
  const required = new Set(Array.isArray(s.required) ? (s.required as string[]) : [])
  // A required field the object does not name would vanish from the type: fail instead.
  for (const r of required) if (!(r in props)) fail(`required field ${r} is not among the object's properties`)
  const entries = Object.entries(props).map(([k, v]) => ({ k, optional: !required.has(k), type: tsType(v) }))
  const fields = entries.map((e) => `${key(e.k)}${e.optional ? '?' : ''}: ${e.type}`)
  // An open object (`additionalProperties` true or a schema) keeps its other fields in the type, beside the named ones.
  // Absent or false, only the named fields are typed.
  const ap = s.additionalProperties
  const extra = ap === true ? 'unknown' : isObj(ap) ? tsType(ap) : null
  if (extra === null) return fields.length === 0 ? 'Record<string, never>' : `{ ${fields.join('; ')} }`
  if (fields.length === 0) return `Record<string, ${extra}>`
  // TypeScript requires every named field to fit the index signature, so it carries their types too.
  const index = extra === 'unknown' ? 'unknown' : union([extra, ...entries.map((e) => e.type), ...(entries.some((e) => e.optional) ? ['undefined'] : [])])
  return `{ ${fields.join('; ')}; [key: string]: ${index} }`
}

/** Every `#/components/schemas/X` rewritten to `#/$defs/X`, the form a JSON Schema validator resolves. */
const toDefs = <T>(x: T): T => JSON.parse(JSON.stringify(x).replaceAll('"#/components/schemas/', '"#/$defs/')) as T

type Param = { name: string; in: string; required?: boolean; schema: Schema }
type Operation = {
  id: string
  method: string
  path: string
  auth: 'owner' | 'client' | 'none'
  pathParams: Param[]
  queryParams: Param[]
  body: Schema | null
  bodyRequired: boolean
  response: Schema
  outputs: Record<string, Schema> | null
}

/** Reads and checks the document: every assumption the client makes is checked here, once. */
export function operationsOf(spec: Spec): Operation[] {
  if (!/^3\.1\./.test(spec.openapi)) fail(`expected OpenAPI 3.1, got ${spec.openapi}`)
  // The version is written into generated source and llms.txt as text, so it must be a version and nothing else.
  if (typeof spec.info?.version !== 'string' || !/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.]+)?$/.test(spec.info.version)) fail(`the API version ${JSON.stringify(spec.info?.version)} is not X.Y.Z`)
  const key = spec.components.securitySchemes?.clientKey
  if (!isObj(key) || key.type !== 'apiKey' || key.in !== 'header' || typeof key.name !== 'string') fail('securitySchemes.clientKey must be an apiKey header')
  const owner = spec.components.securitySchemes?.owner
  if (!isObj(owner) || owner.type !== 'http' || owner.scheme !== 'bearer') fail('securitySchemes.owner must be http bearer')
  errorBody(spec)
  unknownCodes(spec)
  const ops: Operation[] = []
  const seen = new Set<string>()
  for (const [path, item] of Object.entries(spec.paths)) {
    for (const [method, op] of Object.entries(item)) {
      if (!(METHODS as readonly string[]).includes(method)) fail(`unsupported method ${method} on ${path}`)
      const id = typeof op.operationId === 'string' ? ident(op.operationId) : fail(`${method} ${path} has no operationId`)
      if (seen.has(id)) fail(`duplicate operationId ${id}`)
      seen.add(id)
      const security = Array.isArray(op.security) ? (op.security as Schema[]) : fail(`${id} does not state its security`)
      const names = new Set(security.flatMap((r) => Object.keys(r)))
      for (const n of names) if (n !== 'clientKey' && n !== 'owner') fail(`${id}: unknown security scheme ${n}`)
      const params = (Array.isArray(op.parameters) ? op.parameters : []) as unknown as Param[]
      const responses = isObj(op.responses) ? op.responses : fail(`${id} has no responses`)
      const ok = isObj(responses['200']) ? responses['200'] : fail(`${id} has no 200 response`)
      const okSchema = (ok.content as Schema | undefined)?.['application/json'] as Schema | undefined
      if (!isObj(okSchema?.schema)) fail(`${id}: the 200 response is not JSON`)
      for (const [status, r] of Object.entries(responses)) {
        // 304 answers only a conditional request, which this client never makes.
        if (status === '304' && isObj(r) && r.content === undefined) continue
        if (status !== '200' && !(isObj(r) && r.$ref === '#/components/responses/Error')) fail(`${id}: response ${status} is not the shared Error response`)
      }
      let body: Schema | null = null
      let bodyRequired = false
      if (op.requestBody !== undefined) {
        const rb = isObj(op.requestBody) ? op.requestBody : fail(`${id}: requestBody is not an object`)
        const json = ((rb.content as Schema | undefined)?.['application/json'] as Schema | undefined)?.schema
        if (!isObj(json)) fail(`${id}: requestBody has no application/json schema`)
        if (Object.keys(rb.content as Schema).length !== 1) fail(`${id}: requestBody offers a content type other than application/json`)
        body = json as Schema
        bodyRequired = rb.required === true
      }
      const xo = op['x-outputs']
      if (xo !== undefined && !isObj(xo)) fail(`${id}: x-outputs must be an object`)
      const outputs = isObj(xo) ? (xo as Record<string, Schema>) : null
      if (outputs && !params.some((p) => p.in === 'path' && p.name === 'read')) fail(`${id}: x-outputs needs a {read} path parameter`)
      ops.push({
        id,
        method: method.toUpperCase(),
        path,
        auth: names.has('owner') ? 'owner' : names.has('clientKey') ? 'client' : 'none',
        pathParams: params.filter((p) => p.in === 'path'),
        // Headers the API reads (such as if-none-match) are not part of a call's input.
        queryParams: params.filter((p) => p.in === 'query'),
        body,
        bodyRequired,
        response: okSchema!.schema as Schema,
        outputs,
      })
      for (const p of params) if (p.in !== 'path' && p.in !== 'query' && p.in !== 'header') fail(`${id}: parameter ${p.name} in ${p.in}`)
      // A header the API reads is optional (a conditional request); one it requires would be dropped, so it is an error.
      for (const p of params) if (p.in === 'header' && p.required) fail(`${id}: required header ${p.name} is not something this client sends`)
      for (const p of params.filter((x) => x.in === 'path')) if (!path.includes(`{${p.name}}`)) fail(`${id}: path parameter ${p.name} is not in ${path}`)
      // The client fills `{name}` for word names only, and every path value is needed to build the URL.
      for (const p of params.filter((x) => x.in === 'path')) if (!/^\w+$/.test(p.name) || p.required !== true) fail(`${id}: path parameter ${p.name} must be a required word name`)
      for (const m of path.matchAll(/\{([^}]*)\}/g)) if (!params.some((p) => p.in === 'path' && p.name === m[1])) fail(`${id}: ${path} names {${m[1]}}, which is not a path parameter`)
      // A path is joined to the configured origin; one that could name another host (`//host`, a scheme, a backslash)
      // or climb out of it (`..`) would carry the credentials elsewhere.
      if (!/^\/(?!\/)[A-Za-z0-9._~{}\/-]*$/.test(path) || path.split('/').includes('..')) fail(`${id}: path ${path} is not a plain absolute path`)
    }
  }
  return ops.sort((a, b) => a.id.localeCompare(b.id))
}

/** The codes whose outcome must be `unknown` (they may hide a request that moved): x-unknown-codes on the Error response. */
function unknownCodes(spec: Spec): string[] {
  const codes = (spec.components.responses?.Error as Schema | undefined)?.['x-unknown-codes']
  if (!Array.isArray(codes) || codes.length === 0 || !codes.every((c) => typeof c === 'string')) {
    fail('components.responses.Error must carry x-unknown-codes: the codes whose outcome is always unknown')
  }
  return codes as string[]
}

/** The shared error response's body: an object whose `error` property is the error. */
function errorBody(spec: Spec): Schema {
  const r = spec.components.responses?.Error
  const schema = ((r?.content as Schema | undefined)?.['application/json'] as Schema | undefined)?.schema
  if (!isObj(schema) || !isObj((schema.properties as Schema | undefined)?.error) || !(Array.isArray(schema.required) && schema.required.includes('error'))) {
    fail('components.responses.Error must be { error: <the error> }, the body the API sends')
  }
  return schema as Schema
}

const paramType = (ps: Param[]) =>
  ps.length === 0 ? 'never' : `{ ${ps.map((p) => `${key(p.name)}${p.required ? '' : '?'}: ${tsType(p.schema)}`).join('; ')} }`

/** The API's published MCP tool list (spec/tools.json), copied at a release like the document. */
export type ToolListFile = { version: string; tools: readonly { name: string; description: string; exposure: string }[] }
const EXPOSURES = ['public', 'owner'] as const

/** The tools, checked against the document: each is one of its calls, once, offered to the public or the owner. */
function toolsOf(spec: Spec, ops: Operation[], doc: ToolListFile | undefined): ToolListFile['tools'] {
  if (!doc) return []
  if (doc.version !== spec.info.version) fail(`the tool list is API ${doc.version}, the document is ${spec.info.version}`)
  const calls = new Set(ops.map((o) => o.id))
  const seen = new Set<string>()
  for (const t of doc.tools) {
    if (!calls.has(t.name) || t.name.endsWith('_lookup')) fail(`tool ${t.name} is not a call in the document`)
    if (seen.has(t.name)) fail(`tool ${t.name} is listed twice`)
    if (!(EXPOSURES as readonly string[]).includes(t.exposure)) fail(`tool ${t.name} has exposure ${t.exposure}`)
    seen.add(t.name)
  }
  return doc.tools
}

export function generate(spec: Spec, toolDoc?: ToolListFile): Record<string, string> {
  const ops = operationsOf(spec)
  const tools = toolsOf(spec, ops, toolDoc)
  const schemas = spec.components.schemas
  const err = errorBody(spec)
  const types = [
    HEADER,
    `/** Every named shape in the Tempora API ${spec.info.version}. */`,
    ...Object.entries(schemas).map(([n, s]) => `export type ${ident(n)} = ${tsType(s)}`),
    '',
    '/** The error the API returns: the `error` of its error body. */',
    `export type ApiError = ${tsType(((err.properties as Schema).error) as Schema)}`,
    '',
    '/** Per call: its path, query and body inputs (never when it takes none) and its answer. */',
    'export type Operations = {',
    ...ops.map((o) =>
      [
        `  ${o.id}: {`,
        `    path: ${paramType(o.pathParams)}`,
        `    query: ${paramType(o.queryParams)}`,
        `    body: ${o.body ? tsType(o.body) : 'never'}`,
        `    bodyRequired: ${o.bodyRequired}`,
        `    output: ${tsType(o.response)}`,
        `  }`,
      ].join('\n'),
    ),
    '}',
    '',
  ].join('\n')

  const table = Object.fromEntries(
    ops.map((o) => [
      o.id,
      {
        method: o.method,
        path: o.path,
        auth: o.auth,
        response: toDefs(o.response),
        ...(o.outputs ? { outputs: toDefs(o.outputs) } : {}),
      },
    ]),
  )
  const clientKey = spec.components.securitySchemes!.clientKey as Schema
  const runtime = [
    HEADER,
    `/** The API version this client was generated from. */`,
    `export const API_VERSION = ${JSON.stringify(spec.info.version)}`,
    `/** The header that carries the client key. */`,
    `export const CLIENT_KEY_HEADER = ${JSON.stringify(clientKey.name)}`,
    `/** The named shapes, for the run-time answer checks. */`,
    `export const DEFS = ${JSON.stringify(toDefs(schemas))}`,
    `/** The codes whose error outcome is always \`unknown\`: a request may have moved. Any other outcome for them is unreadable. */`,
    `export const UNKNOWN_CODES: readonly string[] = ${JSON.stringify(unknownCodes(spec))}`,
    `/** The error body every non-200 answer carries. */`,
    `export const ERROR_BODY = ${JSON.stringify(toDefs(err))}`,
    `/** Every call: method, path, who may make it, and the schema its answer is checked against. */`,
    `export const OPERATIONS = ${JSON.stringify(table)}`,
    '',
  ].join('\n')

  const toolList = [
    HEADER,
    `/** The MCP tools the API ${spec.info.version} publishes (spec/tools.json): empty until the API has published a list. */`,
    `export const TOOLS = ${JSON.stringify(tools)} as const`,
    '',
  ].join('\n')

  return { 'src/generated/types.ts': types, 'src/generated/spec.ts': runtime, 'src/generated/tools.ts': toolList, 'llms.txt': llms(spec, ops, err, tools) }
}

/** The error codes the document names: the `enum` on the error's `code`, itself or in an `anyOf`/`oneOf` branch, through a $ref. */
export function errorCodes(spec: Spec, err: Schema): string[] {
  const deref = (s: Json | undefined): Schema | undefined =>
    isObj(s) && typeof s.$ref === 'string' ? spec.components.schemas[refName(s.$ref)] : isObj(s) ? s : undefined
  const code = deref((deref((err.properties as Schema).error)?.properties as Schema | undefined)?.code)
  const branches = code ? [code, ...(Array.isArray(code.anyOf) ? code.anyOf : []), ...(Array.isArray(code.oneOf) ? code.oneOf : [])] : []
  const codes = branches.flatMap((b) => (isObj(b) && Array.isArray(b.enum) ? b.enum : []))
  if (codes.length === 0 || !codes.every((c) => typeof c === 'string')) fail('the error body names no error codes: its error.code carries no string enum')
  return codes as string[]
}

function llms(spec: Spec, ops: Operation[], err: Schema, tools: ToolListFile['tools']): string {
  const who = { public: 'anyone', owner: 'the owner' } as Record<string, string>
  // The client key is optional on every call: a wallet owner's own application calls without one.
  const auth = { owner: 'an owner token (and the client key, when the client has one)', client: 'the client key when the client has one; an owner\'s own application signs in without one', none: 'no credentials (the client key is still sent, when the client has one)' } as const
  const input = (o: Operation) => {
    const parts = [o.pathParams.length ? `path: { ${o.pathParams.map((p) => p.name).join(', ')} }` : '', o.queryParams.length ? `query: { ${o.queryParams.map((p) => `${p.name}${p.required ? '' : '?'}`).join(', ')} }` : '', o.body ? `body: ${tsType(o.body)}` : ''].filter(Boolean)
    return `{ ${parts.join(', ')} }`.replace('{  }', '{}')
  }
  return [
    `# @temporalabs/client`,
    '',
    `> The typed client for the Tempora API ${spec.info.version}, over HTTP and MCP. Every call returns a result and never throws; every answer is checked against the API's own schema.`,
    '',
    'This file is generated from the API document in spec/openapi.json. Do not edit it by hand.',
    '',
    '```ts',
    "import { createClient } from '@temporalabs/client'",
    "const client = createClient({ baseUrl: 'https://<api origin>', clientKey: process.env.TEMPORALABS_CLIENT_KEY! })",
    'const r = await client.products({})',
    'if (r.ok) console.log(r.body)',
    'else console.error(r.error.code, r.error.outcome)',
    '```',
    '',
    'The client key is a server-side secret: call the API from a server, never from a browser.',
    '`createClient` also takes `ownerToken` (sent on owner calls), `timeoutMs` and `fetch`; every call takes an optional second argument, `{ ownerToken?, signal? }`, whose `ownerToken` wins over the client\'s.',
    'A result is `{ ok: true, status, body, traceId? }` or `{ ok: false, status, error: { code, message, outcome }, traceId?, retryAfter? }`, where `retryAfter` is the seconds the API asks a caller to wait, when it says.',
    "`outcome` is `refused` (nothing happened), `failed` (nothing happened, try again later) or `unknown` (a write may have gone through: check its status before retrying).",
    '',
    '## Calls',
    '',
    ...ops.map((o) => `- \`client.${o.id}(${input(o)})\`: ${o.method} ${o.path}. Needs ${auth[o.auth]}.${o.id === 'status_lookup' ? ' Pass exactly one of the query keys.' : ''}`),
    '',
    'A `?` marks an optional input.',
    '',
    '## Error codes',
    '',
    'The codes the document names (a later API may add others):',
    '',
    errorCodes(spec, err).map((c) => `\`${c}\``).join(', '),
    '',
    `These always come with outcome \`unknown\` (a request may have moved; any other outcome for them reads as \`unreadable_answer\`): ${unknownCodes(spec).map((c) => `\`${c}\``).join(', ')}.`,
    '',
    'The client adds its own codes. `network_error` (no answer, `status` 0) and `unreadable_answer` (the answer did not match the document) are `unknown` on a POST and `failed` otherwise. `wrong_origin` (the URL would leave the configured origin) and `invalid_path_value` (a path value of `.` or `..`, or one that cannot be written into a URL) are `failed`, with nothing sent and `status` 0. `signIn` adds `challenge_refused`, `signing_failed` and `unsupported_token_type`, and `withOwnerRetry` adds `callback_failed`, all with `status` 0. The MCP client adds `unsupported_protocol` when its endpoint no longer serves this client\'s protocol revision.',
    '',
    '## MCP tools',
    '',
    ...(tools.length === 0
      ? ['None in this API version: the tool list arrives with the API release that publishes it.']
      : [
          "The same calls over the API's MCP endpoint, through `createMcpClient` from `@temporalabs/client/mcp` (same names, same results):",
          '',
          ...tools.map((t) => `- \`${t.name}\` (${who[t.exposure]}): ${t.description}`),
        ]),
    '',
  ].join('\n')
}

/** spec/tools.json under the repository root `root` when the API has published a tool list, otherwise none. */
export function readToolDoc(root: string): ToolListFile | undefined {
  try {
    return JSON.parse(readFileSync(join(root, 'spec', 'tools.json'), 'utf8')) as ToolListFile
  } catch (e) {
    if ((e as { code?: string }).code === 'ENOENT') return undefined
    throw e
  }
}

// Run as a script: write the files.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  // The package is typescript/; the API document it reads is spec/ at the repository root, shared with python/.
  const root = join(dirname(fileURLToPath(import.meta.url)), '..')
  const repo = join(root, '..')
  const spec = JSON.parse(readFileSync(join(repo, 'spec', 'openapi.json'), 'utf8')) as Spec
  const tools = readToolDoc(repo)
  const out = process.argv.includes('--out') ? process.argv[process.argv.indexOf('--out') + 1]! : root
  const files = generate(spec, tools)
  for (const [rel, text] of Object.entries(files)) {
    mkdirSync(dirname(join(out, rel)), { recursive: true })
    writeFileSync(join(out, rel), text)
  }
  console.log(`generate: ${Object.keys(files).length} files from the API ${spec.info.version}`)
}
