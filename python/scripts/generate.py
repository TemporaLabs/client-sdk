def input_type(spec: dict[str, Any], s: Json) -> str:
    """The Python type a caller passes for a path or query value."""
    seen: set[str] = set()
    while is_obj(s) and isinstance(s.get("$ref"), str) and ref_name(s["$ref"]) not in seen:
        seen.add(ref_name(s["$ref"]))
        s = spec["components"]["schemas"].get(ref_name(s["$ref"]))
    if not is_obj(s):
        return "Any"
    if isinstance(s.get("enum"), list) and s["enum"] and all(isinstance(v, str) for v in s["enum"]):
        return f"Literal[{', '.join(repr(v) for v in s['enum'])}]"
    return {"string": "str", "integer": "int", "number": "float", "boolean": "bool"}.get(
        str(s.get("type")), "Any"
    )


def generate(spec: dict[str, Any], tool_doc: dict[str, Any] | None = None) -> dict[str, str]:
    ops = operations_of(spec)
    tools = tools_of(spec, ops, tool_doc)
    schemas: dict[str, Schema] = spec["components"]["schemas"]
    err = error_body(spec)
    error_codes(spec, err)
    version = spec["info"]["version"]

    printer = Printer(schemas)
    for name in schemas:
        printer.claim(ident(name))
    for name in ordered(schemas):
        s = schemas[name]
        printer.taken.discard(name)
        if is_obj(s) and s.get("type") == "object" and s.get("properties") and not any(k in s for k in WHOLE):
            printer.ty(s, name)
        else:
            expr = printer.ty(s, name)
            printer.claim(name)
            printer.blocks.append(f"{name} = {expr}")
    printer.ty(err, "ErrorBody")
    printer.blocks.append(f"ApiError = {printer.ty(err['properties']['error'], printer.claim('ApiError'))}")

    answers: dict[str, tuple[str, dict[str, str] | None]] = {}
    for o in ops:
        base = camel(o.id)
        response = printer.claim(f"{base}Answer")
        printer.blocks.append(f"{response} = {printer.ty(o.response, f'{base}Answer')}")
        outputs = None
        if o.outputs is not None:
            outputs = {}
            for read, schema in o.outputs.items():
                alias = printer.claim(f"{base}{camel(read)}Answer")
                printer.blocks.append(f"{alias} = {printer.ty(schema, alias)}")
                outputs[read] = alias
        answers[o.id] = (response, outputs)
        # Inputs are not checked at run time, but a schema the printer cannot read still fails generation.
        for p in [*o.path_params, *o.query_params]:
            printer.ty(p.get("schema"), "Input", emit=False)
        if o.body is not None:
            printer.ty(o.body, "Input", emit=False)

    models = "\n".join(
        [
            HEADER,
            f'"""Every named shape in the Tempora API {version}, as the answer checks read it."""',
            "",
            "from typing import Annotated, Any, ClassVar, Literal",
            "",
            "from pydantic import ConfigDict, Field",
            "",
            "from .._schema import (",
            "    JsAllOf, JsArray, JsBool, JsEmptyObject, JsLiteral, JsNever,",
            "    JsNumber, JsObject, JsOneOf, JsString,",
            ")",
            "",
            "__all__ = [",
            *[f"    {n!r}," for n in sorted(n for n in printer.taken if n not in IMPORTED)],
            "]",
            "",
            *[f"{b}\n" for b in printer.blocks],
        ]
    )

    client_key = spec["components"]["securitySchemes"]["clientKey"]
    table = []
    for o in ops:
        response, outputs = answers[o.id]
        out = (
            "None"
            if outputs is None
            else "{" + ", ".join(f"{k!r}: models.{v}" for k, v in outputs.items()) + "}"
        )
        table.append(
            f"    {o.id!r}: Operation(method={o.method!r}, path={o.path!r}, auth={o.auth!r}, "
            f"response=models.{response}, outputs={out}),"
        )
    runtime = "\n".join(
        [
            HEADER,
            '"""The API version, the client-key header, the always-`unknown` codes and every call."""',
            "",
            "from dataclasses import dataclass",
            "from typing import Any, Final, Literal",
            "",
            "from . import models",
            "",
            "# The API version this client was generated from.",
            f"API_VERSION: Final = {version!r}",
            "# The header that carries the client key.",
            f"CLIENT_KEY_HEADER: Final = {client_key['name']!r}",
            "# The codes whose error outcome is always `unknown`: a request may have moved.",
            "# Any other outcome for them is unreadable.",
            f"UNKNOWN_CODES: Final[tuple[str, ...]] = {tuple(unknown_codes(spec))!r}",
            "",
            "",
            "@dataclass(frozen=True)",
            "class Operation:",
            '    """One call: its method, path, who may make it, and the type its answer is checked against."""',  # noqa: E501
            "",
            "    method: str",
            "    path: str",
            "    auth: Literal['owner', 'client', 'none']",
            "    response: Any",
            "    # One answer type per read, for a call whose answer depends on its {read} path value.",
            "    outputs: dict[str, Any] | None",
            "",
            "",
            "# The error body every non-2xx answer carries.",
            "ERROR_BODY: Final = models.ErrorBody",
            "# Every call, by its operationId.",
            "OPERATIONS: Final[dict[str, Operation]] = {",
            *table,
            "}",
            "",
        ]
    )

    tools_json = json.dumps(tools, separators=(",", ":"), ensure_ascii=False)
    tool_list = "\n".join(
        [
            HEADER,
            f'"""The MCP tools the API {version} publishes (spec/tools.json).',
            "",
            'Empty until the API has published a list."""',
            "",
            "import json",
            "from typing import Any, Final",
            "",
            f"TOOLS: Final[tuple[dict[str, Any], ...]] = tuple(json.loads({tools_json!r}))",
            "",
        ]
    )

    return {
        "src/generated/__init__.py": f'{HEADER}"""The code generated from the API document."""\n',
        "src/generated/models.py": models,
        "src/generated/spec.py": runtime,
        "src/generated/tools.py": tool_list,
        "src/generated/operations.py": operations_file(spec, ops, answers, tools),
    }


def operations_file(
    spec: dict[str, Any],
    ops: list[Operation],
    answers: dict[str, tuple[str, Any]],
    tools: list[dict[str, Any]],
) -> str:
    """The client's methods as a typed Protocol, with a TypedDict for each call's path and query values."""
    lines = [
        HEADER,
        '"""Each call\'s inputs and answer, for type checkers: the methods `create_client` returns."""',
        "",
        "from collections.abc import Mapping",
        "from typing import Any, Literal, NotRequired, Protocol, TypedDict",
        "",
        "from .._result import Result",
        "from . import models",
        "",
    ]
    methods: dict[str, str] = {}
    for o in ops:
        base = camel(o.id)
        params = ["self", "*"]
        for kind, ps in (("Path", o.path_params), ("Query", o.query_params)):
            if not ps:
                continue
            fields = ", ".join(
                f"{p['name']!r}: "
                + (
                    input_type(spec, p.get("schema"))
                    if p.get("required")
                    else f"NotRequired[{input_type(spec, p.get('schema'))}]"
                )
                for p in ps
            )
            lines += [f"{base}{kind} = TypedDict({base + kind!r}, {{{fields}}})", ""]
            required = any(p.get("required") for p in ps)
            params.append(f"{kind.lower()}: {base}{kind}" + ("" if required else " | None = None"))
        if o.body is not None:
            ref = o.body.get("$ref")
            body_type = f"models.{ref_name(ref)} | Mapping[str, Any]" if isinstance(ref, str) else "Any"
            params.append(f"body: {body_type}" + ("" if o.body_required else " | None = None"))
        params.append("owner_token: str | None = None")
        methods[o.id] = f"    def {o.id}({', '.join(params)}) -> Result[models.{answers[o.id][0]}]: ..."
    names = {t["name"] for t in tools}
    over_mcp = [
        m for name, m in methods.items() if name in names or (name == "status_lookup" and "status" in names)
    ]
    lines += [
        "",
        "class Client(Protocol):",
        '    """One method per call. Every method returns a Result and never raises for an API or network',
        '    problem."""',
        "",
        *methods.values(),
        "",
        "",
        "class McpClient(Protocol):",
        '    """One method per published MCP tool, `status_lookup` beside `status`, and `list_tools`."""',
        "",
        "    def list_tools(self, *, owner_token: str | None = None) -> Result[tuple[dict[str, Any], ...]]: ...",  # noqa: E501
        *over_mcp,
        "",
    ]
    return "\n".join(lines)


def read_tool_doc(root: Path) -> dict[str, Any] | None:
    """spec/tools.json under the repository root when the API has published a tool list, otherwise none."""
    try:
        doc: dict[str, Any] = json.loads((root / "spec" / "tools.json").read_text(encoding="utf-8"))
    except FileNotFoundError:
        return None
    return doc


def main(
    argv: list[str], *, out: Path = PACKAGE, repo: Path = REPO, log: Callable[[str], None] = print
) -> int:
    spec = json.loads((repo / "spec" / "openapi.json").read_text(encoding="utf-8"))
    files = generate(spec, read_tool_doc(repo))
    if "--out" in argv:
        out = Path(argv[argv.index("--out") + 1])
    if "--check" in argv:
        stale = []
        for rel, text in files.items():
            path = out / rel
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(rel)
        generated = out / "src" / "generated"
        for path in sorted(generated.rglob("*")) if generated.exists() else []:
            rel = path.relative_to(out).as_posix()
            if path.is_file() and "__pycache__" not in path.parts and rel not in files:
                stale.append(rel)
        if stale:
            print(
                f"check-generated: not what the API document generates: {', '.join(stale)}. "
                "Run python scripts/generate.py.",
                file=sys.stderr,
            )
            return 1
        log(f"check-generated: {len(files)} files match the API {spec['info']['version']}")
        return 0
    for rel, text in files.items():
        path = out / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    log(f"generate: {len(files)} files from the API {spec['info']['version']}")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv[1:]))
    except GenerateError as e:
        print(e, file=sys.stderr)
        sys.exit(1)
